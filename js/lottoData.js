export const getFullCoOccurrenceMatrix = () => {
    const matrix = Array(46).fill(0).map(() => Array(46).fill(0));
    
    // 분석 스크립트를 통해 산출된 실제 상위 20개 공출현 패턴 (w = 등장 회수)
    const patterns = [
        {a: 11, b: 21, w: 34}, {a: 33, b: 40, w: 33}, {a: 6, b: 38, w: 31}, 
        {a: 12, b: 24, w: 30}, {a: 37, b: 40, w: 29}, {a: 19, b: 21, w: 29}, 
        {a: 3, b: 13, w: 29}, {a: 1, b: 28, w: 29}, {a: 10, b: 31, w: 29}, 
        {a: 3, b: 20, w: 29}, {a: 24, b: 27, w: 29}, {a: 15, b: 34, w: 29}, 
        {a: 34, b: 42, w: 29}, {a: 14, b: 15, w: 28}, {a: 13, b: 33, w: 28}, 
        {a: 3, b: 27, w: 28}, {a: 3, b: 24, w: 28}, {a: 30, b: 34, w: 28}, 
        {a: 8, b: 39, w: 27}, {a: 18, b: 31, w: 27}
    ];

    patterns.forEach(p => {
        matrix[p.a][p.b] = p.w;
        matrix[p.b][p.a] = p.w;
    });

    return matrix;
};

